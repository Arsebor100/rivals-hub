const statusLabels = {
  works: "Works",
  works_but_abandoned: "Works, but abandoned",
  under_review: "Under review",
  broken: "Broken",
  archived: "Archived"
};

let mods = [...initialMods];
let currentLang = "uk";

const modList = document.getElementById("modList");
const statusFilter = document.getElementById("statusFilter");
const modForm = document.getElementById("modForm");
const langButtons = document.querySelectorAll(".lang-btn");

function applyTranslations() {
  const t = translations[currentLang];

  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (t[key]) {
      el.placeholder = t[key];
    }
  });

  const options = statusOptions[currentLang] || statusOptions.en;
  statusFilter.innerHTML = options
    .map((opt) => `<option value="${opt.value}">${opt.label}</option>`)
    .join("");

  statusFilter.value = "all";

  langButtons.forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === currentLang);
  });
}

function getStatusClass(status) {
  return `status-${status}`;
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function renderMods() {
  const selectedStatus = statusFilter.value;

  const visibleMods = mods.filter((mod) => {
    return selectedStatus === "all" || mod.status === selectedStatus;
  });

  modList.innerHTML = "";

  if (!visibleMods.length) {
    const t = translations[currentLang];
    modList.innerHTML = `
      <div class="empty-state">
        <h3>${t.noResults}</h3>
        <p>${t.noResultsText}</p>
      </div>
    `;
    return;
  }

  visibleMods.forEach((mod) => {
    const prosList = (mod.pros || [])
      .map((item) => `<li>${escapeHtml(item)}</li>`)
      .join("");

    const consList = (mod.cons || [])
      .map((item) => `<li>${escapeHtml(item)}</li>`)
      .join("");

    const tags = (mod.tags || [])
      .map((tag) => `<span class="tag">${escapeHtml(tag)}</span>`)
      .join("");

    const t = translations[currentLang];
    const statusText = statusLabels[mod.status] || mod.status;

    const card = `
      <article class="mod-card">
        <div class="card-head">
          <h3 class="card-title">
            <a href="${escapeHtml(mod.placeUrl)}" target="_blank" rel="noreferrer noopener">${escapeHtml(mod.title)}</a>
          </h3>
          <span class="status-badge ${getStatusClass(mod.status)}">${statusText}</span>
        </div>

        <div class="card-meta">
          <span>
            <a href="${escapeHtml(mod.creatorProfileUrl || "#")}" target="_blank" rel="noreferrer noopener" class="creator-link">
              ${t.creatorLabel} ${escapeHtml(mod.creator)}
            </a>
          </span>
          <span>${t.checkedLabel} ${escapeHtml(mod.lastChecked || "Unknown")}</span>
        </div>

        <p class="card-description">${escapeHtml(mod.description)}</p>

        <div class="tags">${tags}</div>

        <div class="data-grid">
          <div class="list-box">
            <h4>${t.prosTitle}</h4>
            <ul>${prosList}</ul>
          </div>

          <div class="list-box">
            <h4>${t.consTitle}</h4>
            <ul>${consList}</ul>
          </div>
        </div>
      </article>
    `;

    modList.insertAdjacentHTML("beforeend", card);
  });
}

function updateStats() {
  const total = mods.length;
  const working = mods.filter((mod) => mod.status === "works").length;
  const review = mods.filter((mod) => mod.status === "under_review").length;
  const archived = mods.filter((mod) => mod.status === "archived").length;

  document.getElementById("stat-projects").textContent = total;
  document.getElementById("stat-working").textContent = working;
  document.getElementById("stat-review").textContent = review;
  document.getElementById("stat-archived").textContent = archived;
}

langButtons.forEach((button) => {
  button.addEventListener("click", () => {
    currentLang = button.dataset.lang;
    applyTranslations();
    renderMods();
  });
});

statusFilter.addEventListener("change", renderMods);

modForm.addEventListener("submit", (event) => {
  event.preventDefault();

  const formData = new FormData(modForm);
  const title = String(formData.get("title") || "").trim();
  const creator = String(formData.get("creator") || "").trim();
  const placeUrl = String(formData.get("placeUrl") || "").trim();
  const status = String(formData.get("status") || "under_review");
  const description = String(formData.get("description") || "").trim();

  const pros = String(formData.get("pros") || "")
    .split(/\n+/)
    .map((line) => line.trim())
    .filter(Boolean);

  const cons = String(formData.get("cons") || "")
    .split(/\n+/)
    .map((line) => line.trim())
    .filter(Boolean);

  if (!title || !creator || !placeUrl || !description) {
    return;
  }

  mods.unshift({
    id: Date.now(),
    title,
    creator,
    creatorProfileUrl: "#",
    placeUrl,
    status,
    description,
    pros,
    cons,
    tags: ["submitted", "community"],
    lastChecked: new Date().toISOString().slice(0, 10),
    verified: false
  });

  modForm.reset();
  updateStats();
  renderMods();
});

applyTranslations();
updateStats();
renderMods();
